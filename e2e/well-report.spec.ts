import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { gotoApp } from "./support/app";

test("well report links supplied depths and preserves report values in print media", async ({ page }) => {
  await gotoApp(page, "/well-report/");
  const report = page.getByTestId("well-report");
  await expect(report).toHaveAttribute("data-well-id", "utah-forge-16a-2021");
  await expect(report.getByRole("heading", { name: "Utah FORGE 16A(78)-32 — As-drilled record" })).toBeVisible();
  await expect(report.getByTestId("well-report-executive-summary")).toContainText("10,987 ft MD on 24 December 2020");
  await expect(report.getByTestId("well-report-executive-summary")).toContainText("10,955 ft MD, leaving the final 32 ft");
  await expect(report.getByTestId("well-report-executive-summary")).toContainText("does not document a production tubing string");
  await expect(report.getByTestId("well-report-executive-summary")).toContainText("two FIT results (9.5 and 9.6 ppg EMW)");
  const overview = report.locator("#well-report-summary");
  await expect(overview.locator('[data-report-field="Reported drilled TD"]')).toContainText("10,987 ft MD");
  await expect(overview.locator('[data-report-field="Last observed survey MD"]')).toContainText("10,955 ft MD");
  await expect(overview).not.toContainText("Measured total depth");
  await expect(report.getByTestId("well-report-logs")).toContainText("7 supplied curves");
  await expect(report.locator("[data-report-section]")).toHaveCount(13);
  await expect(report.locator("#well-report-trajectory")).toBeVisible();
  const studies = report.getByTestId("well-report-studies");
  await expect(studies.getByRole("heading", { name: "Studies, tests, and simulations" })).toBeVisible();
  await expect(studies.locator('[data-report-study="bop-casing-integrity-test"]')).toContainText("All tests were good");
  await expect(studies.locator('[data-report-study="bop-casing-integrity-test"]')).toContainText("5,000 high");
  await expect(studies.locator('[data-report-study="formation-integrity-tests"]')).toContainText("9.5");
  await expect(studies.locator('[data-report-study="formation-integrity-tests"]')).toContainText("9.6");
  await expect(studies.locator('[data-report-study="extended-lot-xlot"]')).toContainText("packer at 7,974 ft failed");
  await expect(studies.locator('[data-report-study="intermediate-hole-step-test"]')).toContainText("157.8");
  await expect(studies.locator('[data-report-study="intermediate-hole-step-test"]')).toContainText("Bit balled; test stopped");
  await expect(studies.locator('[data-report-study="temperature-and-image-logging"]')).toContainText("322");
  await expect(studies.locator('[data-report-study="temperature-and-image-logging"]')).toContainText("Density-neutron, induction resistivity, sonic, FMI");
  await expect(studies.locator('[data-report-study="hydraulics-ecd-simulation"]')).toContainText("No ECD");
  await expect(studies.locator('[data-report-study="reservoir-simulation"]')).toContainText("No reservoir model, numerical simulation");
  const briefing = report.getByTestId("well-report-briefing");
  await expect(briefing.getByText("Trajectory coverage does not reach reported TD")).toBeVisible();
  await expect(briefing.locator('[data-report-highlight="survey-coverage-gap"]')).toContainText("32 ft / 9.8 m");
  await expect(briefing.locator('[data-report-highlight="core-recovery"]')).toContainText("74.4 of 105 ft · 70.9%");
  await expect(briefing.locator('[data-report-highlight="casing-events"]')).toContainText("does not establish present barrier integrity");
  await expect(briefing.locator("[data-drilling-section]")).toHaveCount(3);
  await expect(briefing.locator('[data-drilling-section="production"]')).toContainText("47");
  await expect(briefing.locator('[data-drilling-section="production"]')).toContainText("8");
  await expect(briefing).toContainText("Average ROP (ft/h)");
  await expect(briefing.locator('[data-drilling-section="production"]')).toContainText("28.3");
  await expect(report.getByTestId("well-report-schematic")).toBeVisible();
  const assemblyPair = report.getByTestId("well-report-assembly-pair");
  await expect(assemblyPair).toBeVisible();
  await expect(assemblyPair.getByTestId("assembly-schematic")).toBeVisible();
  const assembly3d = assemblyPair.getByTestId("well-report-assembly-3d").getByTestId("assembly-scene");
  await expect(assembly3d).toBeVisible();
  await expect(assembly3d).toHaveAttribute("data-ready", "true");
  await expect(assembly3d).toHaveAttribute("data-item-count", "7");
  const componentList = report.getByTestId("well-report-component-list");
  await expect(componentList.getByRole("heading", { name: "What is installed, drilled, and cemented" })).toBeVisible();
  await expect(componentList.locator("[data-report-component]")).toHaveCount(10);
  await expect(componentList.locator('[data-component-group="casing"]')).toContainText("Shoe depth (ft MD)");
  await expect(componentList.locator('[data-report-component="production-casing"]')).toContainText("10,787");
  await expect(componentList.locator('[data-component-group="hole"]')).toContainText("Drilled interval (ft MD)");
  await expect(componentList.locator('[data-component-group="surface-equipment"]')).toContainText("dimensions and pressure ratings are not supplied");
  await expect(componentList).toContainText("not to scale");
  const schematicPrecedesOverview = await report.evaluate((article) => {
    const schematic = article.querySelector("#well-report-schematic");
    const overview = article.querySelector("#well-report-summary");
    return Boolean(schematic && overview && (schematic.compareDocumentPosition(overview) & 4));
  });
  expect(schematicPrecedesOverview).toBe(true);
  const trajectory2d5 = report.getByTestId("well-report-trajectory-2-5d");
  await expect(trajectory2d5).toContainText("422 supplied spatial stations");
  await expect(trajectory2d5.locator("[data-construction-record]")).toHaveCount(8);
  await expect(trajectory2d5.locator("[data-construction-component='production-casing']").first()).toBeAttached();
  await expect(trajectory2d5.locator("[data-construction-component='production-hole']").first()).toBeAttached();
  await expect(trajectory2d5).toContainText("OD 177.8 mm");
  await expect(report.locator("[data-report-appendix='survey-source-stations'] tbody tr")).toHaveCount(422);
  await expect(report.locator("[data-report-appendix='service-run-register'] tbody tr").first()).toBeAttached();
  await expect(report.locator("[data-report-appendix='daily-operations-register'] tbody tr").first()).toBeAttached();
  await expect(report.locator('[data-report-row="well-identifiers"]')).toContainText("Operator / UWI");
  await expect(report.getByRole("heading", { name: "Offset-well data" })).toBeVisible();
  await expect(report.locator(".sw-well-report-timeline li").first().locator("small")).toContainText("p. 7");
  await expect(report.getByText("not reported", { exact: true }).first()).toBeVisible();
  await expect(report.locator(".sw-well-report-sources")).toContainText("CC-BY-4.0");
  await expect(page.getByTestId("well-report-link-status")).toContainText("no depth window");

  const trajectory = report.getByTestId("well-report-trajectory").locator('svg[aria-label^="Spatial survey projection"]');
  await trajectory.focus();
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("Enter");
  await expect(page.getByTestId("well-report-link-status")).toContainText("selected 24.4 m MD");

  await report.locator(".sw-well-report-timeline button").first().click();
  await expect(page.getByTestId("well-report-link-status")).toContainText("selected 8.5 m MD");
  const productionCasing = assemblyPair.getByTestId("assembly-schematic").locator('[data-item-id="production-casing"]');
  await componentList.locator('[data-report-component="production-casing"] button').click();
  await expect(productionCasing).toHaveAttribute("aria-pressed", "true");
  await expect(componentList.locator('[data-report-component="production-casing"] button')).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByTestId("well-report-link-status")).toContainText("selected 8.5 m MD");
  await assemblyPair.getByTestId("well-report-assembly-3d").locator(".sw-asm-scene").getByRole("button", { name: "Exploded view" }).click();
  await expect(assembly3d).toHaveAttribute("data-exploded", "true");

  const screenValues = await report.locator("[data-report-value]").allTextContents();
  await page.emulateMedia({ media: "print" });
  await expect(report.locator(".sw-well-report-toolbar")).toBeHidden();
  await expect(page.locator(".demo-nav")).toBeHidden();
  await expect(page.locator(".demo-header")).toBeHidden();
  await expect(report.getByTestId("well-report-trajectory").locator('svg[aria-label^="Trajectory. Measured depth"]')).toBeVisible();
  await expect(report.getByTestId("well-report-trajectory").locator("svg.sw-well-report-plan")).toBeVisible();
  await expect(report.getByTestId("well-report-logs").locator("svg")).toBeVisible();
  const printLayout = await report.evaluate((article) => {
    const wrappers = [...article.querySelectorAll<HTMLElement>(".sw-well-report-table-wrap")];
    const schematicPanels = [...article.querySelectorAll<HTMLElement>(".sw-well-report-assembly-pair > *")];
    return {
      overflowingTables: wrappers.filter((wrapper) => wrapper.scrollWidth > wrapper.clientWidth + 1).length,
      tallestSchematicPanel: Math.max(...schematicPanels.map((panel) => panel.getBoundingClientRect().height)),
    };
  });
  expect(printLayout.overflowingTables).toBe(0);
  expect(printLayout.tallestSchematicPanel).toBeLessThan(320);
  expect(await report.locator("[data-report-value]").allTextContents()).toEqual(screenValues);
  const pdf = await page.pdf({ printBackground: true, preferCSSPageSize: true });
  expect(pdf.subarray(0, 5).toString("ascii")).toBe("%PDF-");
  const pdfDocument = pdf.toString("latin1");
  expect(pdfDocument).toContain("/Font");
  expect([...pdfDocument.matchAll(/\/Type\s*\/Page\b/g)].length).toBeGreaterThan(1);
  const mediaBox = pdfDocument.match(/\/MediaBox\s*\[\s*0\s+0\s+([\d.]+)\s+([\d.]+)\s*\]/);
  expect(mediaBox).not.toBeNull();
  expect(Number(mediaBox?.[1])).toBeGreaterThan(Number(mediaBox?.[2]));
  const axe = await new AxeBuilder({ page }).analyze();
  expect(axe.violations.map((violation) => violation.id)).toEqual([]);
});
