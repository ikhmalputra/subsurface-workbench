// THIRD_PARTY_NOTICES.md, generated: the data sources are hand-kept in docs/third-party/
// data-notices.md; the software comes from the installed dependency graph of every workspace
// package, so the file can never fall behind the lockfile.
//
//   node tools/release/notices.mjs            # rewrite THIRD_PARTY_NOTICES.md
//   node tools/release/notices.mjs --check    # fail if it is out of date, or a licence is not allowed
//
// Allowed licences are the permissive families a client can redistribute. Anything else, or a
// package that states none, fails the check, so a dependency with a copyleft or unknown licence
// cannot slip into a release.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const check = process.argv.includes("--check");
const PERMISSIVE = "MIT|ISC|BSD-[23]-Clause|Apache-2\\.0|0BSD|OFL-1\\.1|CC0-1\\.0|Unlicense|BlueOak-1\\.0\\.0|Python-2\\.0|CC-BY-4\\.0|MPL-2\\.0|Zlib";
const ALLOWED = new RegExp(`^\\(?(${PERMISSIVE})( (OR|AND) (${PERMISSIVE}))*\\)?$`);

/** Every runtime (or, with `--dev`, development) dependency of every workspace package, by name. */
function dependencies(dev) {
  const json = execFileSync("corepack", ["pnpm", "-r", "licenses", "list", dev ? "--dev" : "--prod", "--json"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  const byLicence = JSON.parse(json || "{}");
  const rows = new Map();
  for (const [licence, entries] of Object.entries(byLicence)) for (const entry of entries) {
    const row = rows.get(entry.name) ?? { name: entry.name, versions: new Set(), licence: entry.license || licence, author: entry.author ?? "", homepage: entry.homepage ?? "" };
    for (const version of entry.versions) row.versions.add(version);
    rows.set(entry.name, row);
  }
  return [...rows.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const table = (rows) => ["| Package | Version | Licence | Author |", "|---|---|---|---|",
  ...rows.map((row) => `| ${row.homepage ? `[${row.name}](${row.homepage})` : row.name} | ${[...row.versions].sort().join(", ")} | ${row.licence} | ${row.author.replace(/\|/g, "/")} |`)].join("\n");
const families = (rows) => { const count = new Map(); for (const row of rows) count.set(row.licence, (count.get(row.licence) ?? 0) + 1); return [...count.entries()].sort((a, b) => b[1] - a[1]).map(([licence, n]) => `${licence} (${n})`).join(", "); };

const runtime = dependencies(false), development = dependencies(true);
const disallowed = runtime.filter((row) => !ALLOWED.test(row.licence));
const data = readFileSync(`${root}docs/third-party/data-notices.md`, "utf8").replace(/^<!--[\s\S]*?-->\n*/, "");

const text = `# Third-party notices

Original code and synthetic Blender assets: proprietary, © 2026 Ikhmal Putra Manan, all rights reserved (see LICENSE). The notices below are for third-party software and data, which keep their own licences. No F3 data, PPDM schemas or documentation are bundled.

This file is generated by \`tools/release/notices.mjs\` from the installed dependency graph and from \`docs/third-party/data-notices.md\`; \`node tools/release/notices.mjs --check\` runs in CI, so it cannot fall behind the lockfile.

## Data and models

${data.trim()}

## Software shipped in the deck and the SDK

Every runtime dependency of \`@ikhmalputra/subsurface-core\`, \`@ikhmalputra/subsurface-react\` and the deck, including transitive ones: ${runtime.length} packages. Licence families: ${families(runtime)}. Each package's own licence text is kept in the installed package and in the delivered bundles; retain them when redistributing.

${table(runtime)}

## Development tooling

Not shipped to clients: ${development.length} packages. Licence families: ${families(development)}.

${table(development)}
`;

if (check) {
  let failed = false;
  if (disallowed.length) { console.error(`Licences not allowed for redistribution:\n${disallowed.map((row) => `  ${row.name} ${[...row.versions].join(", ")}: ${row.licence || "(none stated)"}`).join("\n")}`); failed = true; }
  const current = readFileSync(`${root}THIRD_PARTY_NOTICES.md`, "utf8");
  if (current !== text) { console.error("THIRD_PARTY_NOTICES.md is out of date: run `node tools/release/notices.mjs` and commit it."); failed = true; }
  if (!failed) console.log(`Notices current: ${runtime.length} runtime and ${development.length} development packages, all under allowed licences.`);
  process.exit(failed ? 1 : 0);
}
writeFileSync(`${root}THIRD_PARTY_NOTICES.md`, text);
console.log(`Wrote THIRD_PARTY_NOTICES.md: ${runtime.length} runtime and ${development.length} development packages.${disallowed.length ? ` NOT ALLOWED: ${disallowed.map((row) => row.name).join(", ")}` : ""}`);
