import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = resolve(root, "output/packages");
await mkdir(output, { recursive: true });
for (const name of ["@ikhmalputra/subsurface-core", "@ikhmalputra/subsurface-react"]) {
  execFileSync("corepack", ["pnpm", "--filter", name, "pack", "--pack-destination", output], { cwd: root, stdio: "inherit" });
}
// The tarballs are named by each package's own version, so a release bump needs no edit here.
const versionOf = async (dir) => JSON.parse(await readFile(resolve(root, dir, "package.json"), "utf8")).version;
const core = resolve(output, `ikhmalputra-subsurface-core-${await versionOf("packages/core")}.tgz`);
const react = resolve(output, `ikhmalputra-subsurface-react-${await versionOf("packages/react")}.tgz`);
for (const archive of [core, react]) {
  const inventory = execFileSync("tar", ["-tzf", archive], { encoding: "utf8" });
  assert.match(inventory, /package\/LICENSE/);
  assert.match(inventory, /package\/dist\/index.d.ts/);
  assert.doesNotMatch(inventory, /node_modules|\.env|\.blend|fixture|next\.config/);
  if (archive === core) assert.doesNotMatch(inventory, /\.png|\.glb/);
}
const reactInventory = execFileSync("tar", ["-tzf", react], { encoding: "utf8" });
assert.match(reactInventory, /package\/assets\/well-components\/manifest\.json/);
assert.match(reactInventory, /package\/dist\/assembly-scene\.js/);
assert.match(reactInventory, /package\/dist\/site-scene\.js/);
assert.match(reactInventory, /package\/dist\/wells-map\.js/);
assert.match(reactInventory, /package\/assets\/gis\/world-50m\.json/);
assert.match(reactInventory, /package\/dist\/gpu-picker\.js/);
assert.match(reactInventory, /package\/dist\/ui\.d\.ts/);
assert.doesNotMatch(reactInventory, /package\/(?!assets\/well-components\/)[^\n]*\.(png|glb)/);
